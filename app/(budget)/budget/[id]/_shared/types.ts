export const fmt = (n: number) => n === 0 ? "–" : `₹${n.toLocaleString("en-IN")}`;

/** Format a planned-months array as a short chip body: "M1" / "M3, M9". */
export const formatPlannedMonths = (months: number[]) =>
  months.length ? months.map(m => `M${m}`).join(", ") : "—";

export const horizonLabel = (m: number) =>
  m % 12 === 0 ? `${m / 12}-year` : `${m}-month`;
