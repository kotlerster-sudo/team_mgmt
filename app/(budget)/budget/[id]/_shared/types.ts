/** The budget fields both editors need. Each shell extends it with its own. */
export type BudgetCore = {
  id: string;
  name: string;
  domains: string[];
  years: number;
  horizonMonths: number;
  partialPosition?: "start" | "end";
  applyInflation: boolean;
  inflationSalaryPct: number;
  inflationOtherPct: number;
  inflationNilPct: number;
  status: "draft" | "final" | "approved";
  lines: Line[];
  domainLabels?: Record<string, string>;
  inputs?: Record<string, number | string | null> | null;
  workingByLineId?: Record<string, LineWorking>;
};

/** Inflation rate per category as a decimal, zeroed when the budget is flat. */
export function inflationRates(b: Pick<BudgetCore, "applyInflation" | "inflationSalaryPct" | "inflationOtherPct" | "inflationNilPct">): Record<InflationType, number> {
  return b.applyInflation
    ? { Salary: b.inflationSalaryPct / 100, Other: b.inflationOtherPct / 100, Nil: b.inflationNilPct / 100 }
    : { Salary: 0, Other: 0, Nil: 0 };
}

/** Whether the generator's count inputs were filled in — gates the total bars,
 *  which read as a meaningless ₹0 on a budget built line-by-line. */
export function hasCountInputs(inputs: BudgetCore["inputs"]): boolean {
  if (!inputs) return false;
  const { extraInputs, ...top } = inputs as Record<string, unknown>;
  const isCountEntry = ([k, v]: [string, unknown]) => k.startsWith("n") && typeof v === "number" && v > 0;
  return Object.entries(top).some(isCountEntry) ||
    (extraInputs != null && typeof extraInputs === "object" && Object.entries(extraInputs as Record<string, unknown>).some(isCountEntry));
}

export type BandKey = 1 | 2 | 3 | 4 | 5;
export type Band = { k: BandKey; factor: number; label: string };

/** Year-bands present in this horizon, including the pro-rated stub. The stub
 *  is the final band ("end") or Year 1 ("start"). */
export function computeBands(horizonMonths: number, partialPosition: "start" | "end" = "end"): Band[] {
  const fullYears = Math.floor(horizonMonths / 12);
  const tail      = horizonMonths - fullYears * 12;
  const out: Band[] = [];
  const totalBands = tail > 0 ? fullYears + 1 : fullYears;
  for (let k = 1 as BandKey; k <= 5; k = (k + 1) as BandKey) {
    if (k > totalBands) continue;
    if (tail > 0 && partialPosition === "start" && k === 1) {
      out.push({ k, factor: tail / 12, label: `Y1 (${tail}mo)` });
    } else if (tail > 0 && partialPosition === "end" && k === fullYears + 1) {
      out.push({ k, factor: tail / 12, label: `Y${k} (${tail}mo)` });
    } else {
      out.push({ k, factor: 1, label: `Y${k}` });
    }
  }
  return out;
}

